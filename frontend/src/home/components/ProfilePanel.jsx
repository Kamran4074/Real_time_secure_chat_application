import { useEffect, useRef, useState } from 'react';
import axios from 'axios';
import { toast } from 'react-toastify';
import { FiArrowLeft, FiCamera, FiUser, FiAtSign, FiMail, FiTrash2 } from 'react-icons/fi';
import { useAuth } from '../../context/AuthContext';
import Avatar from '../../components/ui/Avatar';
import TextField from '../../components/ui/TextField';
import Button, { Spinner } from '../../components/ui/Button';
import { profileSchema, fieldErrors, serverFieldErrors, MAX_BIO_LENGTH } from '../../validation/authSchemas';
import AccountSettings from './AccountSettings';
import BlockedContacts from './BlockedContacts';

const PHOTO_TYPES = ['image/jpeg', 'image/png', 'image/webp'];
const MAX_PHOTO_MB = 5;
// photos generated by the backend for users without one; nothing to "remove"
const isGeneratedPhoto = (url = '') => url.includes('avatar.iran.liara.run');

const formFrom = (user) => ({ fullname: user?.fullname || '', username: user?.username || '', bio: user?.bio || '' });

// Upload straight to Cloudinary with the parameters our backend signed.
// fetch, not axios: axios would attach our JWT to a request that goes to another site.
const uploadToCloudinary = async (file) => {
    const { data: signed } = await axios.post('/api/user/me/avatar-signature');
    const { uploadUrl, apiKey, signature, ...params } = signed;
    const body = new FormData();
    body.append('file', file);
    body.append('api_key', apiKey);
    body.append('signature', signature);
    Object.entries(params).forEach(([key, value]) => body.append(key, value));

    const res = await fetch(uploadUrl, { method: 'POST', body });
    const json = await res.json().catch(() => ({}));
    if (!res.ok) throw new Error(json?.error?.message || 'Upload failed');
    return json.secure_url;
};

// WhatsApp-style profile drawer that slides over the sidebar
const ProfilePanel = ({ onClose, onSignedOut }) => {
    const { authUser, setAuthUser } = useAuth();
    const [profile, setProfile] = useState(authUser);
    const [form, setForm] = useState(() => formFrom(authUser));
    const [errors, setErrors] = useState({});
    const [saving, setSaving] = useState(false);
    const [photoBusy, setPhotoBusy] = useState(false);
    const fileRef = useRef();

    // bio / email / upload availability are not in the login response, so load the full profile
    useEffect(() => {
        let cancelled = false;
        axios.get('/api/user/me')
            .then(({ data }) => {
                if (cancelled) return;
                setProfile(data);
                setForm(formFrom(data));
            })
            .catch(() => {}); // keep what we have; the 401 interceptor handles expired sessions
        return () => { cancelled = true; };
    }, []);

    useEffect(() => {
        const onKey = (e) => e.key === 'Escape' && onClose();
        window.addEventListener('keydown', onKey);
        return () => window.removeEventListener('keydown', onKey);
    }, [onClose]);

    // keep the session (token) and update what the rest of the app shows
    const applyProfile = (data) => {
        setProfile(data);
        const { fullname, username, profilepic, bio } = data;
        const next = { ...authUser, fullname, username, profilepic, bio };
        localStorage.setItem('chatapp', JSON.stringify(next));
        setAuthUser(next);
    };

    const original = formFrom(profile);
    const changes = Object.fromEntries(
        Object.entries(form).filter(([key, value]) => value.trim() !== original[key])
    );
    const dirty = Object.keys(changes).length > 0;

    const setField = (field) => (e) => {
        setForm((f) => ({ ...f, [field]: e.target.value }));
        setErrors((err) => ({ ...err, [field]: undefined }));
    };

    const handleSave = async (e) => {
        e.preventDefault();
        const result = profileSchema.safeParse(form);
        if (!result.success) return setErrors(fieldErrors(result.error));
        if (!dirty) return;

        setSaving(true);
        try {
            const body = Object.fromEntries(Object.keys(changes).map((key) => [key, result.data[key]]));
            const { data } = await axios.patch('/api/user/me', body);
            applyProfile(data);
            setForm(formFrom(data));
            toast.success('Profile updated');
        } catch (error) {
            const data = error?.response?.data;
            setErrors(serverFieldErrors(data));
            toast.error(data?.message || 'Could not update profile');
        } finally {
            setSaving(false);
        }
    };

    const handlePhoto = async (e) => {
        const file = e.target.files?.[0];
        e.target.value = ''; // picking the same file again should still trigger onChange
        if (!file) return;
        if (!PHOTO_TYPES.includes(file.type)) return toast.error('Use a JPG, PNG or WebP image');
        if (file.size > MAX_PHOTO_MB * 1024 * 1024) return toast.error(`Photo must be under ${MAX_PHOTO_MB} MB`);

        setPhotoBusy(true);
        try {
            const url = await uploadToCloudinary(file);
            const { data } = await axios.patch('/api/user/me', { profilepic: url });
            applyProfile(data);
            toast.success('Photo updated');
        } catch (error) {
            toast.error(error?.response?.data?.message || error.message || 'Could not upload photo');
        } finally {
            setPhotoBusy(false);
        }
    };

    const removePhoto = async () => {
        if (!window.confirm('Remove your profile photo?')) return;
        setPhotoBusy(true);
        try {
            const { data } = await axios.patch('/api/user/me', { profilepic: null });
            applyProfile(data);
            toast.success('Photo removed');
        } catch (error) {
            toast.error(error?.response?.data?.message || 'Could not remove photo');
        } finally {
            setPhotoBusy(false);
        }
    };

    const canUpload = Boolean(profile?.canUploadPhoto);
    const bioLeft = MAX_BIO_LENGTH - form.bio.length;

    return (
        <div role='dialog' aria-modal='true' aria-labelledby='profile-title'
            className='absolute inset-0 z-20 flex flex-col bg-white animate-slide-in motion-reduce:animate-none'>
            <header className='flex items-center gap-3 border-b border-slate-200 px-4 py-4'>
                <button onClick={onClose} aria-label='Close profile'
                    className='grid h-9 w-9 place-items-center rounded-lg text-slate-600 transition hover:bg-slate-100'>
                    <FiArrowLeft className='h-5 w-5' />
                </button>
                <h2 id='profile-title' className='text-lg font-semibold text-slate-900'>Profile</h2>
            </header>

            <div className='scroll-thin flex-1 overflow-y-auto'>
                <section className='flex flex-col items-center bg-slate-50 px-5 py-7'>
                    <button type='button' disabled={!canUpload || photoBusy} onClick={() => fileRef.current?.click()}
                        aria-label='Change profile photo' title={canUpload ? 'Change photo' : undefined}
                        className='group relative rounded-full focus:outline-none focus-visible:ring-4 focus-visible:ring-brand-500/30 disabled:cursor-default'>
                        <Avatar user={profile} size='xl' />
                        {(canUpload || photoBusy) && (
                            <span className={`absolute inset-0 grid place-items-center rounded-full bg-slate-900/50 text-white transition
                                ${photoBusy ? 'opacity-100' : 'opacity-0 group-hover:opacity-100 group-focus-visible:opacity-100'}`}>
                                {photoBusy ? <Spinner /> : (
                                    <span className='flex flex-col items-center gap-1 text-xs font-semibold'>
                                        <FiCamera className='h-6 w-6' /> Change photo
                                    </span>
                                )}
                            </span>
                        )}
                    </button>
                    <input ref={fileRef} type='file' accept={PHOTO_TYPES.join(',')} onChange={handlePhoto} className='hidden'
                        data-testid='photo-input' />
                    <div className='mt-3 flex gap-4 text-sm'>
                        {canUpload && (
                            <button type='button' disabled={photoBusy} onClick={() => fileRef.current?.click()}
                                className='font-semibold text-brand-600 hover:text-brand-700 disabled:opacity-50'>
                                Upload photo
                            </button>
                        )}
                        {profile?.profilepic && !isGeneratedPhoto(profile.profilepic) && (
                            <button type='button' disabled={photoBusy} onClick={removePhoto}
                                className='inline-flex items-center gap-1 font-semibold text-rose-600 hover:text-rose-700 disabled:opacity-50'>
                                <FiTrash2 aria-hidden /> Remove
                            </button>
                        )}
                    </div>
                </section>

                <form onSubmit={handleSave} noValidate className='space-y-5 px-5 py-6'>
                    <TextField id='profile-fullname' label='Name' icon={FiUser} maxLength={60}
                        value={form.fullname} onChange={setField('fullname')} error={errors.fullname} />
                    <TextField id='profile-username' label='Username' icon={FiAtSign} maxLength={20} autoCapitalize='none'
                        value={form.username} onChange={setField('username')} error={errors.username}
                        hint='People find you by this. Letters, numbers, _ or .' />

                    <div>
                        <label htmlFor='profile-bio' className='mb-1.5 block text-sm font-medium text-slate-700'>About</label>
                        <textarea id='profile-bio' rows={3} maxLength={MAX_BIO_LENGTH} value={form.bio} onChange={setField('bio')}
                            placeholder='Hey there! I am using ChatWave.'
                            aria-invalid={errors.bio ? true : undefined}
                            className={`w-full resize-none rounded-xl border bg-white px-3.5 py-2.5 text-[15px] text-slate-900 shadow-sm
                                placeholder:text-slate-400 transition focus:outline-none focus:ring-4
                                ${errors.bio ? 'border-rose-400 focus:ring-rose-500/15' : 'border-slate-300 focus:border-brand-500 focus:ring-brand-500/15'}`} />
                        <p className={`mt-1 text-right text-xs ${bioLeft < 10 ? 'text-amber-600' : 'text-slate-400'}`}>
                            {errors.bio || `${bioLeft} left`}
                        </p>
                    </div>

                    <div>
                        <p className='mb-1.5 text-sm font-medium text-slate-700'>Email</p>
                        <p className='flex items-center gap-2 rounded-xl bg-slate-100 px-3.5 py-2.5 text-[15px] text-slate-600'>
                            <FiMail aria-hidden className='shrink-0 text-slate-400' />
                            <span className='truncate'>{profile?.email || '—'}</span>
                        </p>
                        <p className='mt-1.5 text-xs text-slate-500'>Only you can see your email.</p>
                    </div>

                    <Button type='submit' loading={saving} disabled={!dirty}>
                        {saving ? 'Saving…' : 'Save changes'}
                    </Button>
                </form>

                <AccountSettings profile={profile} onSignedOut={onSignedOut} />
                <BlockedContacts />
            </div>
        </div>
    );
};

export default ProfilePanel;
